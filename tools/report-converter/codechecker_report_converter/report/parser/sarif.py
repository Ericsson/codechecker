"""
Parse the sarif (v2.1.0) output of an analyzer and convert reports to sarif.

The sarif files written by CodeChecker are a lossless representation of the
CodeChecker report model (see docs/tools/sarif.md). CodeChecker specific
information is stored in standard extension points of sarif:
'partialFingerprints' (§3.27.17) and property bags (§3.8).
"""

import json
import logging
import os
import traceback

from pathlib import PurePosixPath
from typing import Any
from urllib.parse import quote, unquote, urlparse

from codechecker_report_converter.report import BugPathEvent, \
    BugPathPosition, File, MacroExpansion, get_or_create_file, Range, Report
from codechecker_report_converter.report.hash import get_report_hash, HashType
from codechecker_report_converter.report.parser.base import AnalyzerInfo, \
    BaseParser, get_tool_info


EXTENSION = 'sarif'

SARIF_VERSION = "2.1.0"
SARIF_SCHEMA = "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/" \
    "master/Schemata/sarif-schema-2.1.0.json"

# Key of the CodeChecker report hash in 'result.partialFingerprints'.
REPORT_HASH_KEY = "codeCheckerReportHash/v1"

# Key in property bags which identifies the kind of a CodeChecker specific
# sarif object (thread flow, related location).
KIND_KEY = "codeChecker.kind"
KIND_BUG_PATH_POSITIONS = "bugPathPositions"
KIND_NOTE = "note"
KIND_MACRO_EXPANSION = "macroExpansion"

# Location property which stores the line and column of a bug path event,
# note or macro expansion if it differs from the start of its range.
POSITION_KEY = "codeChecker.position"

# Run name used for reports without analyzer name ('driver.name' is
# mandatory in sarif).
UNKNOWN_ANALYZER = "unknown"

# Base id for relative URIs (e.g. after --trim-path-prefix).
SRCROOT = "SRCROOT"


LOG = logging.getLogger('report-converter')


# §3.37
class ThreadFlowInfo:
    def __init__(self):
        self.bug_path_events: list[BugPathEvent] = []
        self.bug_path_positions: list[BugPathPosition] = []


class _RunContext:
    """ Data of the currently parsed run (§3.14). """
    def __init__(self, run: dict):
        self.rules: dict[str, dict] = {}
        driver = run.get("tool", {}).get("driver", {})
        for rule in driver.get("rules", []):
            self.rules[rule["id"]] = rule

        # Sarif files generated by CodeChecker contain this property.
        self.generated_by_codechecker = \
            "generatedBy" in driver.get("properties", {})

        self.analyzer_name: str | None = driver.get("name", UNKNOWN_ANALYZER)
        if self.generated_by_codechecker and \
                self.analyzer_name == UNKNOWN_ANALYZER:
            self.analyzer_name = None

        # §3.14.14
        self.original_uri_base_ids: dict | None = \
            run.get("originalUriBaseIds")

        # §3.14.15
        self.artifacts: list[dict] = run.get("artifacts", [])


# Parse to/from sarif formats.
# Sarif has an extensive documentation, and supports a grand number of fields
# that CodeChecker has no use for as of writing this comment (e.g. §3.39
# graph), leading to these fields to be ignored.
# This is NOT (and will likely never be) a full fledged sarif parser, only what
# we need from it at the time.
class Parser(BaseParser):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.result_file_path = ""
        self.had_error = False
        self._source_dir_path: str | None = None

    def get_reports(
        self,
        analyzer_result_file_path: str,
        source_dir_path: str | None = None
    ) -> list[Report]:
        """ Get reports from the given analyzer result file. """
        reports: list[Report] = []
        self.result_file_path = analyzer_result_file_path
        self.had_error = False
        self._source_dir_path = source_dir_path

        data = self._load(analyzer_result_file_path)
        if not data:
            return reports

        try:
            for run in data.get("runs") or []:
                ctx = _RunContext(run)

                for result in run.get("results") or []:
                    for report in self._create_reports(result, ctx):
                        if self.had_error:
                            return []

                        if report.report_hash is None:
                            report.report_hash = get_report_hash(
                                report, HashType.PATH_SENSITIVE)

                        reports.append(report)
        except Exception as ex:
            LOG.warning("Error during processing reports from the sarif "
                        "file: %s", analyzer_result_file_path)
            traceback.print_exc()
            LOG.warning(type(ex))
            LOG.warning(ex)
            return []

        return reports

    def _load(self, path: str) -> dict | None:
        """ Load the given sarif file. """
        try:
            with open(path, 'r', encoding='utf-8', errors='ignore') as f:
                data = json.load(f)
        except OSError as ex:
            LOG.warning("Failed to open sarif file: %s", path)
            LOG.warning(ex)
            return None
        except ValueError as ex:
            LOG.warning("%s is not a valid sarif file.", path)
            LOG.warning(ex)
            return None

        if not isinstance(data, dict):
            LOG.warning("%s is not a valid sarif file.", path)
            return None

        return data

    def _create_reports(
        self,
        result: dict,
        ctx: _RunContext
    ) -> list[Report]:
        """ Create reports from the given result object (§3.27). """
        reports: list[Report] = []

        rule_id = result["ruleId"]
        props = result.get("properties", {})
        severity = self.get_severity(rule_id) or props.get("severity")
        message = self._process_message(
            result["message"], rule_id, ctx.rules)  # §3.11

        report_hash = result.get("partialFingerprints", {}) \
            .get(REPORT_HASH_KEY)

        thread_flow_info = self._process_code_flows(result, rule_id, ctx)
        notes, macro_expansions = self._process_related_locations(
            result, rule_id, ctx)

        for location in result.get("locations", []):
            # TODO: We don't really support non-local analyses, so we
            # only parse physical locations here.
            file, rng = self._process_location(location, ctx)
            if self.had_error:
                return []
            if not (file and rng):
                continue

            bug_path_events = thread_flow_info.bug_path_events or None

            report = Report(
                file, rng.start_line, rng.start_col,
                message, rule_id,
                severity=severity,
                report_hash=report_hash,
                analyzer_name=ctx.analyzer_name,
                category=props.get("category"),
                type=props.get("type"),
                analyzer_result_file_path=self.result_file_path,
                bug_path_events=bug_path_events,
                bug_path_positions=thread_flow_info.bug_path_positions,
                notes=notes,
                macro_expansions=macro_expansions,
                annotations=props.get("annotations"))

            reports.append(report)

        return reports

    def _process_code_flows(
        self,
        result: dict,
        rule_id: str,
        ctx: _RunContext
    ) -> ThreadFlowInfo:
        """
        Parse threadFlows (§3.36.3), which is a list of threadFlow objects
        (§3.37), basically the components of a bug path (events, arrows).
        """
        thread_flow_info = ThreadFlowInfo()

        for code_flow in result.get("codeFlows", []):
            for thread_flow in code_flow.get("threadFlows", []):
                kind = thread_flow.get("properties", {}).get(KIND_KEY)
                is_positions = kind == KIND_BUG_PATH_POSITIONS

                for location_data in thread_flow["locations"]:
                    location = location_data["location"]

                    if is_positions:
                        file, rng = self._process_location(location, ctx)
                        if file:
                            thread_flow_info.bug_path_positions.append(
                                BugPathPosition(file, rng))
                        continue

                    if "message" not in location:
                        continue

                    event = self._create_event(
                        location, rule_id, ctx, BugPathEvent)
                    if event:
                        thread_flow_info.bug_path_events.append(event)

        return thread_flow_info

    def _process_related_locations(
        self,
        result: dict,
        rule_id: str,
        ctx: _RunContext
    ) -> tuple[list[BugPathEvent], list[MacroExpansion]]:
        """
        Parse relatedLocations (§3.27.22). Notes and macro expansions written
        by CodeChecker are stored here.
        """
        notes: list[BugPathEvent] = []
        macro_expansions: list[MacroExpansion] = []

        for location in result.get("relatedLocations", []):
            if "message" not in location:
                continue

            kind = location.get("properties", {}).get(KIND_KEY)
            if kind == KIND_MACRO_EXPANSION:
                macro = self._create_event(
                    location, rule_id, ctx, MacroExpansion)
                if macro:
                    macro_expansions.append(macro)
            elif kind == KIND_NOTE:
                note = self._create_event(
                    location, rule_id, ctx, BugPathEvent)
                if note:
                    notes.append(note)

        return notes, macro_expansions

    def _create_event(
        self,
        location: dict,
        rule_id: str,
        ctx: _RunContext,
        cls: type
    ) -> Any:
        """
        Create a bug path event, note or macro expansion from the given
        location (§3.28).
        """
        file, rng = self._process_location(location, ctx)
        if not (file and rng):
            return None

        message = self._process_message(
            location["message"], rule_id, ctx.rules)

        props = location.get("properties", {})
        line, column = rng.start_line, rng.start_col
        position = props.get(POSITION_KEY)
        if position:
            line = position.get("line", line)
            column = position.get("column", column)

        # Files generated by CodeChecker do not contain the end of the region
        # if the original object had no range.
        region = location["physicalLocation"].get("region", {})
        file_range: Range | None = rng
        if ctx.generated_by_codechecker and "endLine" not in region:
            file_range = None

        if cls is MacroExpansion:
            return MacroExpansion(
                message, props.get("name", ""), file, line, column,
                file_range)

        return BugPathEvent(message, file, line, column, file_range)

    def _process_location(
        self,
        location: dict,
        ctx: _RunContext
    ) -> tuple[File | None, Range | None]:
        """
        Parse location (§3.28). Currently we only parse physical locations
        (§3.29), that describe a (file, range) pair, among other things.
        Sarif also supports logical locations (§3.33) that might describe
        a namespace, type, etc, but CodeChecker has no use for that.
        """
        physical_loc = location.get("physicalLocation")
        if physical_loc:
            file = self._get_file(physical_loc, ctx)
            rng = self._get_range(physical_loc)
            return file, rng

        return None, None

    def _get_range(self, physical_loc: dict) -> Range | None:
        """ Get range from a physical location. """
        region = physical_loc.get("region", {})
        start_line = region.get("startLine")
        if start_line is None:
            return None

        start_col = region.get("startColumn", 1)
        end_line = region.get("endLine", start_line)
        end_col = region.get("endColumn", start_col)

        return Range(start_line, start_col, end_line, end_col)

    def _resolve_uri_base_id(
        self,
        uri_base_id: str,
        postfix: str,
        ctx: _RunContext
    ) -> str | None:
        """
        Try to assemble the leading part of the URI needed to find out the
        absolute path of the file. If this fails, we consider the entire sarif
        file invalid, not only this particular record.

        Returns None if the base id can not be resolved but the file was
        generated by CodeChecker, so relative paths are allowed.
        """
        original_uri_base_ids = ctx.original_uri_base_ids or {}
        original = original_uri_base_ids.get(uri_base_id)

        if not original and ctx.generated_by_codechecker:
            # CodeChecker writes relative URIs without base (e.g. when
            # --trim-path-prefix is used).
            return None

        error_str = \
            f"Failed to fully resolve the path for '{postfix}'. sarif " \
            "v2.1.0 permits this, but CodeChecker requires it to be " \
            "available. If you intend to hide the absolute path before " \
            "storing the results to a CodeChecker server, use " \
            "--trim-path-prefix."

        if not ctx.original_uri_base_ids:
            LOG.error("Missing 'originalUriBaseIds' (sarif v2.1.0 §3.14.14) "
                      "in '%s'.", self.result_file_path)
            LOG.error(error_str)
            self.had_error = True
            return ""

        if not original:
            LOG.error("Missing entry for '%s in "
                      "'originalUriBaseIds' (sarif v2.1.0 §3.14.14) in '%s'.",
                      uri_base_id,
                      self.result_file_path)
            LOG.error(error_str)
            self.had_error = True
            return ""

        abs_uri_prefix = original.get("uri")
        if not abs_uri_prefix:
            LOG.warning("Missing 'uri' (sarif v2.1.0 §3.4.3) for "
                        "'%s in 'originalUriBaseIds' (sarif "
                        "v2.1.0 §3.14.14) in '%s'.",
                        uri_base_id,
                        self.result_file_path)
            LOG.error(error_str)
            self.had_error = True
            return ""

        if "uriBaseId" in original:
            prefix = self._resolve_uri_base_id(
                original["uriBaseId"], postfix, ctx)
            if prefix is None:
                return abs_uri_prefix
            return prefix + abs_uri_prefix
        return abs_uri_prefix

    def _get_file(
        self,
        physical_loc: dict,
        ctx: _RunContext
    ) -> File | None:
        """
        Assemble the artifact location (§3.4) for physical_loc. Sarif files
        contain a lot of relative references, but also contains everything
        needed to resolve an absolute path for the file.
        """
        artifact_loc = physical_loc.get("artifactLocation")
        if not artifact_loc:
            return None

        uri = artifact_loc.get("uri")
        uri_base_id = artifact_loc.get("uriBaseId")

        # §3.4.5: the location may only refer to an entry in 'artifacts'.
        index = artifact_loc.get("index")
        if uri is None and index is not None and \
                0 <= index < len(ctx.artifacts):
            artifact_loc = ctx.artifacts[index].get("location", {})
            uri = artifact_loc.get("uri")
            uri_base_id = artifact_loc.get("uriBaseId")

        if uri is None:
            return None

        if uri_base_id:
            prefix = self._resolve_uri_base_id(uri_base_id, uri, ctx)
            if prefix is not None:
                uri = prefix + uri

        uri_parsed = urlparse(uri)
        if uri_parsed is None:
            LOG.warning("Failed to urlparse %s!", uri)
            return None

        file_path = unquote(os.path.join(uri_parsed.netloc, uri_parsed.path))

        if self._source_dir_path and not os.path.isabs(file_path):
            file_path = os.path.normpath(
                os.path.join(self._source_dir_path, file_path))

        return get_or_create_file(file_path, self._file_cache)

    def _process_message(
        self,
        msg: dict,
        rule_id: str,
        rules: dict[str, dict]
    ) -> str:
        """
        Parse message (§3.11). Sometimes, the warning message is attributed to
        the checker (or rule, as is called here) under messageStrings
        (§3.49.11), which might need a little extra parsing.
        """
        if "text" in msg:
            return msg["text"]

        args = msg.get("arguments", [])

        rule = rules[rule_id]
        message_strings = rule.get("messageStrings", {})
        return message_strings[msg["id"]]["text"].format(*args)

    def convert(
        self,
        reports: list[Report],
        analyzer_info: AnalyzerInfo | None = None
    ):
        """
        Converts the given reports to sarif format. A separate run is created
        for each analyzer.
        """
        default_analyzer = analyzer_info.name if analyzer_info else None

        reports_by_analyzer: dict[str, list[Report]] = {}
        for report in reports:
            analyzer_name = report.analyzer_name or default_analyzer or \
                UNKNOWN_ANALYZER
            reports_by_analyzer.setdefault(analyzer_name, []).append(report)

        return {
            "version": SARIF_VERSION,
            "$schema": SARIF_SCHEMA,
            "runs": [
                self._create_run(analyzer_name, analyzer_reports)
                for analyzer_name, analyzer_reports
                in sorted(reports_by_analyzer.items())]
        }

    def _create_run(
        self,
        analyzer_name: str,
        reports: list[Report]
    ) -> dict:
        """ Create a run object (§3.14) for the reports of one analyzer. """
        tool_name, tool_version = get_tool_info()

        rules: dict[str, dict] = {}
        rule_indices: dict[str, int] = {}
        artifact_indices: dict[str, int] = {}
        artifacts: list[dict] = []
        results: list[dict] = []

        for report in reports:
            checker_name = report.checker_name
            if checker_name not in rules:
                rule_indices[checker_name] = len(rules)
                rules[checker_name] = self._create_rule(report)

            for file in sorted(report.files, key=lambda f: f.path):
                if file.path not in artifact_indices:
                    artifact_indices[file.path] = len(artifacts)
                    artifacts.append({
                        "location": self._create_artifact_location(file)})

            results.append(self._create_result(
                report, rule_indices[checker_name], artifact_indices))

        run: dict[str, Any] = {
            "tool": {
                "driver": {
                    "name": analyzer_name,
                    "rules": list(rules.values()),
                    "properties": {
                        "generatedBy": {
                            "name": tool_name,
                            "version": tool_version
                        }
                    }
                }
            },
            "artifacts": artifacts,
            "results": results
        }

        return run

    def _create_rule(self, report: Report) -> dict:
        """ Create a reportingDescriptor object (§3.49) for a checker. """
        checker_name = report.checker_name
        rule: dict[str, Any] = {
            "id": checker_name,
            "fullDescription": {
                "text": report.message
            }
        }

        checker_labels = self._checker_labels
        if checker_labels:
            doc_url = checker_labels.label_of_checker(
                checker_name, "doc_url", report.analyzer_name)
            if doc_url:
                if isinstance(doc_url, list):
                    doc_url = doc_url[0]
                rule["helpUri"] = doc_url

            severity = checker_labels.severity(
                checker_name, report.analyzer_name)
            if severity:
                rule["defaultConfiguration"] = {
                    "level": self._to_level(severity)
                }

        return rule

    def _get_severity(self, report: Report) -> str | None:
        """ Get severity of the given report. """
        if report.severity:
            return report.severity

        if self._checker_labels:
            return self._checker_labels.severity(
                report.checker_name, report.analyzer_name)

        return None

    def _create_result(
        self,
        report: Report,
        rule_index: int,
        artifact_indices: dict[str, int]
    ) -> dict:
        """ Create result dictionary from the given report. """
        main_range = self._get_main_range(report)

        result: dict[str, Any] = {
            "ruleId": report.checker_name,
            "ruleIndex": rule_index,
            "message": {
                "text": report.message
            },
            "locations": [{
                "physicalLocation": self._create_physical_location(
                    report.file, main_range, artifact_indices)
            }]
        }

        # The report hash is copied verbatim, it must never be recomputed.
        if report.report_hash is not None:
            result["partialFingerprints"] = {
                REPORT_HASH_KEY: report.report_hash
            }

        severity = self._get_severity(report)
        if severity:
            level = self._to_level(severity)
            if level:
                result["level"] = level

        # Set `suppressions` property.
        if (rs := report.review_status) and rs.status != "unreviewed":
            suppression = {}

            if rs.in_source:
                suppression["kind"] = "inSource"
            else:
                suppression["kind"] = "external"

            if rs.status in ["suppress", "false_positive", "intentional"]:
                suppression["status"] = "accepted"
            elif rs.status == "confirmed":
                suppression["status"] = "rejected"

            suppression["justification"] = rs.message.decode('utf-8')

            result["suppressions"] = [suppression]

        # Set `codeFlows` property.
        thread_flows: list[dict[str, Any]] = []

        if report.bug_path_events:
            thread_flows.append({"locations": [
                self._create_thread_flow_location(
                    self._create_event_location(event, artifact_indices),
                    "important")
                for event in report.bug_path_events]})

        if report.bug_path_positions:
            thread_flows.append({
                "properties": {KIND_KEY: KIND_BUG_PATH_POSITIONS},
                "locations": [
                    self._create_thread_flow_location({
                        "physicalLocation": self._create_physical_location(
                            pos.file, pos.range, artifact_indices)})
                    for pos in report.bug_path_positions]})

        if thread_flows:
            result["codeFlows"] = [{"threadFlows": thread_flows}]

        # Set `relatedLocations` property.
        related_locations = []
        for note in report.notes:
            location = self._create_event_location(note, artifact_indices)
            location.setdefault("properties", {})[KIND_KEY] = KIND_NOTE
            related_locations.append(location)

        for macro in report.macro_expansions:
            location = self._create_event_location(macro, artifact_indices)
            location.setdefault("properties", {}).update({
                KIND_KEY: KIND_MACRO_EXPANSION,
                "name": macro.name})
            related_locations.append(location)

        if related_locations:
            for idx, location in enumerate(related_locations):
                location["id"] = idx
            result["relatedLocations"] = related_locations

        # Set CodeChecker specific properties.
        properties: dict[str, Any] = {}
        if severity:
            properties["severity"] = severity
        if report.category is not None:
            properties["category"] = report.category
        if report.type is not None:
            properties["type"] = report.type
        if report.annotations:
            properties["annotations"] = dict(report.annotations)

        if properties:
            result["properties"] = properties

        return result

    def _get_main_range(self, report: Report) -> Range:
        """
        The report model has no range for the main location. Use the range of
        the last bug path event at the main location (this is the main event)
        if available.
        """
        for event in reversed(report.bug_path_events):
            if event.range and event.file == report.file and \
                    event.line == report.line and \
                    event.column == report.column and \
                    event.range.start_line == report.line and \
                    event.range.start_col == report.column:
                return event.range

        return Range(report.line, report.column, report.line, report.column)

    def _create_thread_flow_location(
        self,
        location: dict,
        importance: str | None = None
    ) -> dict[str, Any]:
        """ Create a threadFlowLocation object (§3.38). """
        thread_flow_location: dict[str, Any] = {"location": location}
        if importance:
            thread_flow_location["importance"] = importance
        return thread_flow_location

    def _create_event_location(
        self,
        event: BugPathEvent,
        artifact_indices: dict[str, int]
    ) -> dict[str, Any]:
        """
        Create location (§3.28) from a bug path event, note or macro
        expansion.
        """
        rng = event.range
        if rng is None:
            region: dict[str, int] = {
                "startLine": event.line,
                "startColumn": event.column
            }
            physical_location = self._create_physical_location(
                event.file, None, artifact_indices, region)
        else:
            physical_location = self._create_physical_location(
                event.file, rng, artifact_indices)

        location: dict[str, Any] = {
            "physicalLocation": physical_location,
            "message": {"text": event.message}
        }

        # Store the position of the event if it differs from its range.
        if rng is not None and \
                (rng.start_line != event.line or
                 rng.start_col != event.column):
            location["properties"] = {
                POSITION_KEY: {"line": event.line, "column": event.column}
            }

        return location

    def _create_physical_location(
        self,
        file: File,
        rng: Range | None,
        artifact_indices: dict[str, int],
        region: dict[str, int] | None = None
    ) -> dict[str, Any]:
        """ Create physicalLocation (§3.29) object. """
        artifact_location = self._create_artifact_location(file)
        artifact_location["index"] = artifact_indices[file.path]

        physical_location: dict[str, Any] = {
            "artifactLocation": artifact_location
        }

        if rng:
            region = {
                "startLine": rng.start_line,
                "startColumn": rng.start_col,
                "endLine": rng.end_line,
                "endColumn": rng.end_col,
            }

        if region:
            physical_location["region"] = region

        return physical_location

    def _create_artifact_location(self, file: File) -> dict[str, Any]:
        """
        Create artifactLocation (§3.4) object. The (possibly trimmed) file
        path is used. Absolute paths are converted to 'file' URIs, relative
        paths are written as relative references with 'SRCROOT' base id.
        """
        path = file.path
        if os.path.isabs(path):
            return {"uri": PurePosixPath(path).as_uri()}

        return {"uri": quote(path), "uriBaseId": SRCROOT}

    def _to_level(self, severity: str) -> str | None:
        """ Map severity label value to level (§3.50.3). """
        if severity in ["HIGH", "CRITICAL"]:
            return "error"
        elif severity == "MEDIUM":
            return "warning"
        elif severity in ["STYLE", "LOW"]:
            return "note"
        elif severity == "UNSPECIFIED":
            return "warning"  # sarif spec recommendation
        else:
            return None

    def write(self, data: Any, output_file_path: str):
        """ Creates an analyzer output file from the given data. """
        try:
            with open(output_file_path, 'w',
                      encoding="utf-8", errors="ignore") as f:
                json.dump(data, f)
        except TypeError as err:
            LOG.error('Failed to write sarif file: %s', output_file_path)
            LOG.error(err)
            traceback.print_exc()

    def replace_report_hash(
        self,
        analyzer_result_file_path: str,
        hash_type=HashType.CONTEXT_FREE
    ):
        """
        Override hash in the given file by using the given version hash.
        """
        self.result_file_path = analyzer_result_file_path
        self.had_error = False
        self._source_dir_path = None

        data = self._load(analyzer_result_file_path)
        if not data:
            return

        try:
            for run in data.get("runs") or []:
                ctx = _RunContext(run)
                for result in run.get("results") or []:
                    reports = self._create_reports(result, ctx)
                    if self.had_error:
                        return
                    if not reports:
                        continue

                    result.setdefault("partialFingerprints", {})[
                        REPORT_HASH_KEY] = get_report_hash(
                            reports[0], hash_type)
        except Exception as ex:
            LOG.warning("Error during processing reports from the sarif "
                        "file: %s", analyzer_result_file_path)
            traceback.print_exc()
            LOG.warning(type(ex))
            LOG.warning(ex)
            return

        self.write(data, analyzer_result_file_path)
